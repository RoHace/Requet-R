-- Montants : multiples de 0,25. Dates : texte AAAA-MM-JJ. Identifiants : categories 1-7, produits 101-130, clients 201-240, commandes 1001-1070.
PRAGMA foreign_keys = ON;

CREATE TABLE categories (
  id  INTEGER PRIMARY KEY,
  nom TEXT NOT NULL UNIQUE
);

CREATE TABLE produits (
  id           INTEGER PRIMARY KEY,
  nom          TEXT NOT NULL,
  categorie_id INTEGER NOT NULL,
  prix         REAL NOT NULL CHECK (prix > 0),
  stock        INTEGER NOT NULL CHECK (stock >= 0),
  FOREIGN KEY (categorie_id) REFERENCES categories (id)
);

CREATE TABLE clients (
  id               INTEGER PRIMARY KEY,
  prenom           TEXT NOT NULL,
  nom              TEXT NOT NULL,
  email            TEXT NOT NULL UNIQUE,
  ville            TEXT,
  date_inscription DATE NOT NULL,
  parrain_id       INTEGER,
  FOREIGN KEY (parrain_id) REFERENCES clients (id)
);

CREATE TABLE commandes (
  id             INTEGER PRIMARY KEY,
  client_id      INTEGER NOT NULL,
  date_commande  DATE NOT NULL,
  statut         TEXT NOT NULL CHECK (statut IN ('en_preparation', 'expediee', 'livree', 'annulee', 'retournee')),
  frais_port     REAL NOT NULL CHECK (frais_port >= 0),
  date_livraison DATE,
  note           INTEGER CHECK (note BETWEEN 1 AND 5),
  FOREIGN KEY (client_id) REFERENCES clients (id)
);

CREATE TABLE lignes_commande (
  commande_id   INTEGER NOT NULL,
  produit_id    INTEGER NOT NULL,
  quantite      INTEGER NOT NULL CHECK (quantite > 0),
  prix_unitaire REAL NOT NULL CHECK (prix_unitaire > 0),
  PRIMARY KEY (commande_id, produit_id),
  FOREIGN KEY (commande_id) REFERENCES commandes (id),
  FOREIGN KEY (produit_id) REFERENCES produits (id)
);

